-- total sales in beauty products
select shopify_sales_data.product_id, shopify_sales_data.quantity,
shopify_sales_data.product_category, shopify_sales_data.profit , 
shopify_sales_data.product_price,
(shopify_sales_data.product_price*shopify_sales_data.quantity) as total_sales 
from shopify_sales_data
where shopify_sales_data.product_category='Beauty' --AND shopify_sales_data.customer_country='Australia'
order by shopify_sales_data.product_id, shopify_sales_data.product_category; 

-- total sales of beauty products in australia 

select shopify_sales_data.product_id, shopify_sales_data.quantity,
shopify_sales_data.product_category, shopify_sales_data.profit , 
shopify_sales_data.product_price,
shopify_sales_data.customer_country, 
(shopify_sales_data.product_price*shopify_sales_data.quantity) as total_sales 
from shopify_sales_data
where shopify_sales_data.product_category='Beauty' AND shopify_sales_data.customer_country='Australia'
order by shopify_sales_data.product_id, shopify_sales_data.product_category; 

-- to check whether a product is returned or not 

select * from shopify_sales_data
where shopify_sales_data.is_returned=0;

-- country names 

select shopify_sales_data.customer_country 
from shopify_sales_data
group by shopify_sales_data.customer_country; 


-- total revenue by product category
select shopify_sales_data.product_category, SUM(shopify_sales_data.revenue) as [total revenue]
from shopify_sales_data
group by shopify_sales_data.product_category
order by [total revenue] DESC; 

select * from shopify_sales_data; 

-- highest rated product 

select shopify_sales_data.product_category,count(shopify_sales_data.rating) as [Top rated product] 
from shopify_sales_data
group by shopify_sales_data.product_category
order by [top rated product] desc; 

-- maximum discounted product 
select shopify_sales_data.product_category, max(shopify_sales_data.discounted_price) as [Maximum discount ]
from shopify_sales_data
group by shopify_sales_data.product_category
order by [Maximum discount ] DESC; 

-- TOTAL REVENUE GENERATED BY EACH PRODUCT 
select shopify_sales_data.product_id, shopify_sales_data.product_category, shopify_sales_data.customer_country , sum(shopify_sales_data.revenue) as [Total Revenue ]
from shopify_sales_data
group by shopify_sales_data.customer_country, shopify_sales_data.product_id, shopify_sales_data.product_category, shopify_sales_data.product_price
order by shopify_sales_data.customer_country asc , shopify_sales_data.product_id; 

-- countrywise total revenue 
select  shopify_sales_data.customer_country , sum(shopify_sales_data.revenue) as [Total Revenue ]
from shopify_sales_data
group by shopify_sales_data.customer_country 
order by shopify_sales_data.customer_country asc;  

-- Countrywise total profit 
select  shopify_sales_data.customer_country , sum(shopify_sales_data.profit) as [Total Profit ]
from shopify_sales_data
group by shopify_sales_data.customer_country 
order by shopify_sales_data.customer_country asc;  

-- payment anaysis 
select shopify_sales_data.payment_method, sum(shopify_sales_data.shipping_cost) as [total shipping cost]
from shopify_sales_data
group by shopify_sales_data.payment_method
order by [total shipping cost] DESC;  

-- Buying methods analysis 
select shopify_sales_data.traffic_source , shopify_sales_data.customer_country, sum(shopify_sales_data.revenue) as [Total Revenue]
from shopify_sales_data
group by shopify_sales_data.traffic_source  , shopify_sales_data.customer_country--, shopify_sales_data.revenue
order by shopify_sales_data.customer_country asc; 

